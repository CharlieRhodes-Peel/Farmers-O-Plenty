// Buildscript for every `versions/*-neoforge` project (see settings.gradle.kts).
// Version-specific values come from versions/<version>/gradle.properties.
plugins {
    `java-library`
    `maven-publish`
    idea
    id("net.neoforged.moddev")
    id("minecraft-artifacts-mutex")
}

val modId = property("mod_id") as String

version = "${property("mod_version")}+${sc.current.version}-neoforge"
group = property("mod_group_id") as String

base {
    archivesName = modId
}

// Mojang ships Java 21 to end users in 1.21.1, so mods should target Java 21.
java.toolchain.languageVersion = JavaLanguageVersion.of(21)

// Datagen output is per version, since the generated JSON differs between Minecraft versions.
val generatedResources = file("src/generated/resources")

sourceSets.main {
    resources {
        // Include resources generated by data generators.
        srcDir(generatedResources)

        // Exclude common development only resources from finalized outputs
        exclude("**/*.bbmodel") // BlockBench project files
        exclude(".cache/**") // datagen cache files
    }
}

repositories {
    // Add here additional repositories if required by some of the dependencies below.
    maven("https://maven.createmod.net")
    maven("https://maven.ithundxr.dev/snapshots")
    maven("https://www.cursemaven.com")
    maven("https://api.modrinth.com/maven") {
        content { includeGroup("maven.modrinth") }
    }
}

neoForge {
    // Specify the version of NeoForge to use.
    version = property("neo_version") as String

    parchment {
        mappingsVersion = property("parchment_mappings_version") as String
        minecraftVersion = property("parchment_minecraft_version") as String
    }

    // Default run configurations.
    // These can be tweaked, removed, or duplicated as needed.
    runs {
        register("client") {
            client()

            // Comma-separated list of namespaces to load gametests from. Empty = all namespaces.
            systemProperty("neoforge.enabledGameTestNamespaces", modId)
        }

        register("server") {
            server()
            programArgument("--nogui")
            systemProperty("neoforge.enabledGameTestNamespaces", modId)
        }

        // This run config launches GameTestServer and runs all registered gametests, then exits.
        // By default, the server will crash when no gametests are provided.
        // The gametest system is also enabled by default for other run configs under the /test command.
        register("gameTestServer") {
            type = "gameTestServer"
            systemProperty("neoforge.enabledGameTestNamespaces", modId)
        }

        register("data") {
            data()

            // Specify the modid for data generation, where to output the resulting resource, and where to look for existing resources.
            programArguments.addAll(
                "--mod", modId, "--all",
                "--output", generatedResources.absolutePath,
                "--existing", rootProject.file("src/main/resources").absolutePath,
            )
        }

        // applies to all the run configs above
        configureEach {
            // Keeps using the original run/ folder (and its worlds) from before the multi-version setup.
            gameDirectory = rootProject.file("run")

            // Recommended logging data for a userdev environment
            // The markers can be added/remove as needed separated by commas.
            // "SCAN": For mods scan.
            // "REGISTRIES": For firing of registry events.
            // "REGISTRYDUMP": For getting the contents of all registries.
            systemProperty("forge.logging.markers", "REGISTRIES")

            // Recommended logging level for the console
            // You can set various levels here.
            // Please read: https://stackoverflow.com/questions/2031163/when-to-use-the-different-log-levels
            logLevel = org.slf4j.event.Level.DEBUG
        }
    }

    mods {
        // define mod <-> source bindings
        // these are used to tell the game which sources are for which mod
        // multi mod projects should define one per mod
        register(modId) {
            sourceSet(sourceSets.main.get())
        }
    }
}

// Sets up a dependency configuration called 'localRuntime'.
// This configuration should be used instead of 'runtimeOnly' to declare
// a dependency that will be present for runtime testing but that is
// "optional", meaning it will not be pulled by dependents of this mod.
val localRuntime: Configuration by configurations.creating
configurations.runtimeClasspath { extendsFrom(localRuntime) }

dependencies {
    implementation(property("deps.biomesoplenty") as String)
    implementation(property("deps.terrablender") as String)
    implementation(property("deps.glitchcore") as String)

    implementation(property("deps.farmersdelight") as String)

    //JEI optional dependency for an easier time!
    compileOnly(property("deps.jei") as String)
    localRuntime(property("deps.jei") as String)

    runtimeOnly("maven.modrinth:sodium:Pb3OXVqC")   // Sodium 0.8.13 (NeoForge 1.21.1)
    runtimeOnly("maven.modrinth:iris:t3ruzodq")     // Iris 1.8.14-beta.1 (NeoForge 1.21.1)
}

// This block of code expands all declared replace properties in the specified resource targets.
// A missing property will result in an error. Properties are expanded using ${} Groovy notation.
val replaceProperties = listOf(
    "minecraft_version", "minecraft_version_range", "neo_version", "loader_version_range",
    "mod_id", "mod_name", "mod_license", "mod_version",
).associateWith { property(it) as String }
val generateModMetadata = tasks.register<ProcessResources>("generateModMetadata") {
    inputs.properties(replaceProperties)
    expand(replaceProperties)
    from(rootProject.file("src/main/templates/neoforge"))
    into(layout.buildDirectory.dir("generated/sources/modMetadata"))
}
// Include the output of "generateModMetadata" as an input directory for the build
// this works with both building through Gradle and the IDE.
sourceSets.main { resources.srcDir(generateModMetadata) }
// To avoid having to run "generateModMetadata" manually, make it run on every project reload
neoForge.ideSyncTask(generateModMetadata)

tasks.named("createMinecraftArtifacts") {
    // Stonecutter must write this version's copy of src/ before Minecraft is set up against it.
    dependsOn("stonecutterGenerate")
}

// Example configuration to allow publishing using the maven-publish plugin
publishing {
    publications {
        register<MavenPublication>("mavenJava") {
            from(components["java"])
        }
    }
    repositories {
        maven("file://${rootProject.projectDir}/repo")
    }
}

tasks.withType<JavaCompile>().configureEach {
    options.encoding = "UTF-8" // Use the UTF-8 charset for Java compilation
}

// IDEA no longer automatically downloads sources/javadoc jars for dependencies, so we need to explicitly enable the behavior.
idea {
    module {
        isDownloadSources = true
        isDownloadJavadoc = true
    }
}
