// Buildscript for every `versions/*-forge` project (see settings.gradle.kts).
// Version-specific values come from versions/<version>/gradle.properties.
// Uses ModDevGradle's legacy Forge plugin: https://github.com/neoforged/ModDevGradle/blob/main/LEGACY.md
plugins {
    `java-library`
    `maven-publish`
    idea
    id("net.neoforged.moddev.legacyforge")
    id("minecraft-artifacts-mutex")
}

val modId = property("mod_id") as String

version = "${property("mod_version")}+${sc.current.version}-forge"
group = property("mod_group_id") as String

base {
    archivesName = modId
}

// Minecraft 1.20.1 runs on Java 17.
java.toolchain.languageVersion = JavaLanguageVersion.of(17)

// Datagen output is per version, since the generated JSON differs between Minecraft versions.
val generatedResources = file("src/generated/resources")

sourceSets.main {
    resources {
        // Include resources generated by data generators.
        srcDir(generatedResources)

        // Exclude common development only resources from finalized outputs
        exclude("**/*.bbmodel") // BlockBench project files
        exclude(".cache/**") // datagen cache files
    }
}

repositories {
    maven("https://www.cursemaven.com")
    maven("https://api.modrinth.com/maven") {
        content { includeGroup("maven.modrinth") }
    }
}

legacyForge {
    version = "${property("minecraft_version")}-${property("forge_version")}"

    parchment {
        mappingsVersion = property("parchment_mappings_version") as String
        minecraftVersion = property("parchment_minecraft_version") as String
    }

    runs {
        register("client") {
            client()
        }

        register("server") {
            server()
            programArgument("--nogui")
        }

        register("data") {
            data()

            // Specify the modid for data generation, where to output the resulting resource, and where to look for existing resources.
            programArguments.addAll(
                "--mod", modId, "--all",
                "--output", generatedResources.absolutePath,
                "--existing", rootProject.file("src/main/resources").absolutePath,
            )
        }

        // applies to all the run configs above
        configureEach {
            // Game folder is versions/1.20.1-forge/run, kept apart from the 1.21.1 worlds and configs.
            systemProperty("forge.logging.markers", "REGISTRIES")
            logLevel = org.slf4j.event.Level.DEBUG
        }
    }

    mods {
        register(modId) {
            sourceSet(sourceSets.main.get())
        }
    }
}

// Same as on NeoForge: runtime-only mods for testing that dependents of this mod don't inherit.
val localRuntime: Configuration by configurations.creating
configurations.runtimeClasspath { extendsFrom(localRuntime) }
// Published 1.20.1 mods are in SRG names; the mod* configurations remap them to Mojang names.
// They are NOT transitive, so every mod's own dependencies must be listed too.
// This adds a remapping "modLocalRuntime" next to the built-in modImplementation, modCompileOnly, etc.
obfuscation {
    createRemappingConfiguration(localRuntime)
}

dependencies {
    modImplementation(property("deps.biomesoplenty") as String)
    modImplementation(property("deps.terrablender") as String)
    modImplementation(property("deps.glitchcore") as String)

    modImplementation(property("deps.farmersdelight") as String)

    //JEI optional dependency for an easier time!
    modCompileOnly(property("deps.jei") as String)
    "modLocalRuntime"(property("deps.jei") as String)
}

// Forge 1.20.1 reads META-INF/mods.toml (not neoforge.mods.toml) and wants a pack.mcmeta.
val replaceProperties = listOf(
    "minecraft_version", "minecraft_version_range", "forge_version", "loader_version_range",
    "mod_id", "mod_name", "mod_license", "mod_version",
).associateWith { property(it) as String }
val generateModMetadata = tasks.register<ProcessResources>("generateModMetadata") {
    inputs.properties(replaceProperties)
    expand(replaceProperties)
    from(rootProject.file("src/main/templates/forge"))
    into(layout.buildDirectory.dir("generated/sources/modMetadata"))
}
sourceSets.main { resources.srcDir(generateModMetadata) }
legacyForge.ideSyncTask(generateModMetadata)

tasks.named("createMinecraftArtifacts") {
    // Stonecutter must write this version's copy of src/ before Minecraft is set up against it.
    dependsOn("stonecutterGenerate")
}

publishing {
    publications {
        register<MavenPublication>("mavenJava") {
            from(components["java"])
        }
    }
    repositories {
        maven("file://${rootProject.projectDir}/repo")
    }
}

tasks.withType<JavaCompile>().configureEach {
    options.encoding = "UTF-8"
}

idea {
    module {
        isDownloadSources = true
        isDownloadJavadoc = true
    }
}
